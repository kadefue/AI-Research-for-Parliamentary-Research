    for f in raw_tex_files:
        print(f"  - {f.name}")
    print("----------------------------------------------------------------------")
    
    results = []
    
    for raw_f in raw_tex_files:
        print(f"\n[Processing] Rectifying {raw_f.name}...")
        rectified_content = rectify_file(raw_f)
        
        target_tex = MANUALS_DIR / raw_f.name

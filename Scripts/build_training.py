def ensure_logo_assets():
    """Ensures Coat of arms SVG is converted to high-res PNG and vector PDF."""
    svg_path = LOGO_DIR / "Coat_of_arms_of_Tanzania.svg"
    png_path = LOGO_DIR / "Coat_of_arms_of_Tanzania.png"
    pdf_path = LOGO_DIR / "Coat_of_arms_of_Tanzania.pdf"

    if svg_path.exists() and (not png_path.exists() or not pdf_path.exists()):
        print("Converting Coat_of_arms_of_Tanzania.svg to PNG and PDF...")
        try:
            import fitz
            doc = fitz.open(str(svg_path))
            pix = doc[0].get_pixmap(dpi=300)
            pix.save(str(png_path))
            
            pdf_bytes = doc.convert_to_pdf()
            pdf_doc = fitz.open("pdf", pdf_bytes)
            pdf_doc.save(str(pdf_path))
            print(f"Successfully generated: {png_path.name} and {pdf_path.name}")
        except Exception as e:
            print(f"PyMuPDF conversion notice: {e}")

    # Ensure symlinks exist in Training_Manuals for seamless path resolution
    manuals_logo = MANUALS_DIR / "Logo"
    if not manuals_logo.exists():
        manuals_logo.symlink_to(Path("../../Logo"), target_is_directory=True)

    manuals_figs = MANUALS_DIR / "figures"
    if not manuals_figs.exists():
        manuals_figs.symlink_to(Path("../figures"), target_is_directory=True)


def ensure_figures():
    """Runs build_figures.py to ensure all high-resolution figures exist."""
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    build_fig_script = SCRIPTS_DIR / "build_figures.py"
    if build_fig_script.exists():
        print("Invoking build_figures.py...")
        res = subprocess.run([sys.executable, str(build_fig_script), str(FIGURES_DIR)],
                             capture_output=True, text=True)
        if res.returncode != 0:
            print(f"Error in build_figures.py:\n{res.stderr}")
        else:
            print("Figures validated successfully.")


